"use client";

import React, { useEffect, useMemo, useRef, useState } from "react";
import { Code2, Download, Expand, Hand, Minimize, Minus, Network, Plus, Scan, Table2 } from "lucide-react";
import { cn } from "@/lib/cn";

interface DbSchemaViewerProps {
  mermaid: string;
  diagram?: string;
}

type ViewMode = "diagram" | "source";

/** Watches the `.dark` class on <html> so the diagram re-renders in the right theme. */
function useIsDark() {
  const [dark, setDark] = useState(false);
  useEffect(() => {
    const el = document.documentElement;
    const update = () => setDark(el.classList.contains("dark"));
    update();
    const mo = new MutationObserver(update);
    mo.observe(el, { attributes: true, attributeFilter: ["class"] });
    return () => mo.disconnect();
  }, []);
  return dark;
}

export default function DbSchemaViewer({ mermaid: mermaidSource }: DbSchemaViewerProps) {
  const [mode, setMode] = useState<ViewMode>("diagram");
  const [isExpanded, setIsExpanded] = useState(false);
  const [mermaidSvg, setMermaidSvg] = useState<string>("");
  const [svgDimensions, setSvgDimensions] = useState({ width: 0, height: 0 });
  const [isLoaded, setIsLoaded] = useState(false);
  const containerRef = useRef<HTMLDivElement>(null);
  const dark = useIsDark();

  const [scale, setScale] = useState(1);
  const [position, setPosition] = useState({ x: 0, y: 0 });
  const [isDragging, setIsDragging] = useState(false);
  const [parseError, setParseError] = useState<string | null>(null);
  const [dragStart, setDragStart] = useState({ x: 0, y: 0 });
  const [highlight, setHighlight] = useState<string | null>(null);

  // Strip markdown fences if the LLM output wrapped it in a code block, and strip carriage returns
  const rawSource = mermaidSource.replace(/```mermaid/g, '').replace(/```/g, '').replace(/\r/g, '').trim();

  const lines = rawSource.split('\n');
  const cleanedLines = lines.map(line => {
    let cleaned = line;
    
    // Ensure there is a space before '{' if the AI forgot it (e.g. "Client{" -> "Client {")
    // We only add space if it's not preceded by 'o' or '|' (cardinality), or whitespace
    cleaned = cleaned.replace(/([^o|\s])\{/g, '$1 {');
    
    // e.g. " |{ " or "|{" (without dashes or dots) -> " ||--o{ "
    cleaned = cleaned.replace(/(?<![-.])\s*\|\{\s*/g, ' ||--o{ ');
    
    // e.g. " }| " or "}|" (without dashes or dots) -> " }o--|| "
    cleaned = cleaned.replace(/\s*\}\|\s*(?![-.])/g, ' }o--|| ');

    // Fix LLM generating two relationships joined by .. (e.g. }o--|| .. ||--o{)
    cleaned = cleaned.replace(/--\|\|\s*\.\.\s*\|\|--/g, '--');

    // Fix invalid single-character cardinalities generated by some LLMs
    // Left side single | or o
    cleaned = cleaned.replace(/(?<=\s)\|--/g, '||--');
    cleaned = cleaned.replace(/(?<=\s)\|\.\./g, '||..');
    cleaned = cleaned.replace(/(?<=\s)o--/g, '}o--');
    cleaned = cleaned.replace(/(?<=\s)o\.\./g, '}o..');
    
    // Right side single | or o
    cleaned = cleaned.replace(/--\|(?=\s)/g, '--||');
    cleaned = cleaned.replace(/\.\.\|(?=\s)/g, '..||');
    cleaned = cleaned.replace(/--o(?=\s)/g, '--o{');
    cleaned = cleaned.replace(/\.\.o(?=\s)/g, '..o{');

    // If it has a colon, it's a relationship label. Fix unquoted labels.
    const isRelationshipLike = cleaned.match(/(?:\|o|\|\||\}o|\}\|)(?:\-\-|\.\.)(?:o\||\|\||o\{|\|\{)/);
    if (cleaned.includes(':') && (!cleaned.includes('{') || isRelationshipLike)) {
      // Strip trailing brace if the LLM wrongly wrapped the relationship line
      cleaned = cleaned.replace(/\}\s*$/, '');
      
      // Add quotes if the label is unquoted (and doesn't already have quotes)
      if (!cleaned.match(/:\s*".*"$/)) {
        cleaned = cleaned.replace(/:\s*([^"\n\r]+)\s*$/, (match, p1) => {
            return ': "' + p1.trim() + '"';
        });
      }
    }
    
    return cleaned;
  });

  // Second pass: ensure entity blocks are closed if the LLM forgot the closing brace
  let inEntityBlock = false;
  const finalLines: string[] = [];

  for (let line of cleanedLines) {
    const trimmed = line.trim();
    // ER diagram relationship operators MUST have left cardinality, line, and right cardinality.
    const isRelationship = line.match(/(?:\|o|\|\||\}o|\}\|)(?:\-\-|\.\.)(?:o\||\|\||o\{|\|\{)/);
    
    // If we hit a relationship line but are still inside an entity block, close it!
    if (isRelationship && inEntityBlock) {
      finalLines.push('}');
      inEntityBlock = false;
    }
    
    if (trimmed === '}') {
      if (!inEntityBlock) continue; // Skip extra closing brace if we already closed it
      inEntityBlock = false;
    } else if (trimmed.endsWith('{') && !isRelationship) {
      // Entity start (works even if the entity name is quoted like "User Account" {)
      inEntityBlock = true;
    }
    
    finalLines.push(line);
  }

  // Close any remaining open block
  if (inEntityBlock) {
    finalLines.push('}');
  }

  let cleanSource = finalLines.join('\n');

  const processedMermaid = cleanSource.includes("direction")
    ? cleanSource
    : cleanSource.replace("erDiagram", "erDiagram\n    direction LR\n");

  // Tables and relationship count, for the summary and the table chips.
  const { entities, relationshipCount } = useMemo(() => {
    const names = new Set<string>();
    let rels = 0;
    for (const line of processedMermaid.split("\n")) {
      const t = line.trim();
      const ent = t.match(/^"?([\w ]+?)"?\s*\{$/);
      if (ent) names.add(ent[1].trim());
      const rel = t.match(/^"?([\w ]+?)"?\s+[|}o][|o{}]?(?:--|\.\.)[|o{}][|o{}]?\s+"?([\w ]+?)"?\s*:/);
      if (rel) {
        rels++;
        names.add(rel[1].trim());
        names.add(rel[2].trim());
      }
    }
    return { entities: [...names], relationshipCount: rels };
  }, [processedMermaid]);

  const fitToScreen = (svgWidth: number, svgHeight: number) => {
    if (!containerRef.current || svgWidth === 0 || svgHeight === 0) return;
    const padding = 60;
    const scaleX = (containerRef.current.clientWidth - padding) / svgWidth;
    const scaleY = (containerRef.current.clientHeight - padding) / svgHeight;
    setScale(Math.min(scaleX, scaleY, 1.5));
    setPosition({ x: 0, y: 0 });
  };

  useEffect(() => {
    if (!processedMermaid.trim().startsWith("erDiagram")) return;

    const renderMermaid = async () => {
      setIsLoaded(false);
      const id = `er-diag-${Math.random().toString(36).substring(2, 11)}`;
      try {
        setParseError(null);
        const mermaid = (await import("mermaid")).default;
        mermaid.initialize({
          startOnLoad: false,
          theme: dark ? "dark" : "neutral",
          er: {
            useMaxWidth: false,
            diagramPadding: 60,
            layoutDirection: "LR",
            minEntityHeight: 32,
            minEntityWidth: 200,
            entityPadding: 15,
            fontSize: 12,
          },
          fontFamily: '"Geist Mono", monospace',
        });

        const { svg } = await mermaid.render(id, processedMermaid);
        const doc = new DOMParser().parseFromString(svg, "image/svg+xml");
        const svgEl = doc.querySelector("svg");

        if (svgEl) {
          const vb = svgEl.getAttribute("viewBox");
          let vbX = 0, vbY = 0, width = 0, height = 0;
          if (vb) {
            const parts = vb.split(/[\s,]+/);
            vbX = parseFloat(parts[0]) || 0;
            vbY = parseFloat(parts[1]) || 0;
            width = parseFloat(parts[2]) || 0;
            height = parseFloat(parts[3]) || 0;
          }
          // Pad the viewBox so labels at the edges aren't clipped.
          const margin = 40;
          const totalW = width + margin * 2;
          const totalH = height + margin * 2;
          svgEl.setAttribute("viewBox", `${vbX - margin} ${vbY - margin} ${totalW} ${totalH}`);
          svgEl.setAttribute("width", `${totalW}px`);
          svgEl.setAttribute("height", `${totalH}px`);
          svgEl.style.maxWidth = "none";
          svgEl.style.overflow = "visible";
          setMermaidSvg(new XMLSerializer().serializeToString(svgEl));
          setSvgDimensions({ width: totalW, height: totalH });
        } else {
          setMermaidSvg(svg);
        }
        setTimeout(() => setIsLoaded(true), 50);
      } catch (error) {
        console.error("Mermaid rendering error:", error);
        // Mermaid leaves error SVGs in <body> when it fails; remove them so the layout doesn't jump.
        document.querySelectorAll(`[id^="d${id}"]`).forEach((node) => node.remove());
        setParseError(String(error));
      }
    };

    renderMermaid();
  }, [processedMermaid, dark]);

  useEffect(() => {
    if (!isLoaded || svgDimensions.width === 0 || !containerRef.current) return;
    const observer = new ResizeObserver(() => fitToScreen(svgDimensions.width, svgDimensions.height));
    observer.observe(containerRef.current);
    fitToScreen(svgDimensions.width, svgDimensions.height);
    return () => observer.disconnect();
  }, [isLoaded, svgDimensions.width, svgDimensions.height, isExpanded]);

  // Ctrl/⌘ + wheel zooms; plain wheel keeps scrolling the chat.
  useEffect(() => {
    const el = containerRef.current;
    if (!el) return;
    const onWheel = (e: WheelEvent) => {
      if (!e.ctrlKey && !e.metaKey) return;
      e.preventDefault();
      setScale((s) => Math.min(5, Math.max(0.1, s * (e.deltaY < 0 ? 1.1 : 0.9))));
    };
    el.addEventListener("wheel", onWheel, { passive: false });
    return () => el.removeEventListener("wheel", onWheel);
  }, [mode, parseError]);

  const onPointerDown = (e: React.PointerEvent) => {
    if (mode === "source") return;
    (e.target as Element).setPointerCapture?.(e.pointerId);
    setIsDragging(true);
    setDragStart({ x: e.clientX - position.x, y: e.clientY - position.y });
  };
  const onPointerMove = (e: React.PointerEvent) => {
    if (!isDragging) return;
    setPosition({ x: e.clientX - dragStart.x, y: e.clientY - dragStart.y });
  };
  const stopDrag = () => setIsDragging(false);

  const zoomIn = () => setScale((s) => Math.min(s + 0.25, 5));
  const zoomOut = () => setScale((s) => Math.max(s - 0.25, 0.1));

  const downloadSvg = () => {
    if (!mermaidSvg) return;
    const url = URL.createObjectURL(new Blob([mermaidSvg], { type: "image/svg+xml" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = "database-schema.svg";
    a.click();
    URL.revokeObjectURL(url);
  };

  // Highlighted source view.
  const formatSource = (raw: string): React.ReactNode[] => {
    const formatted = raw.replace(/(\w+)\s*\{([^}]+)\}/g, (_m, name, body) => {
      const attrs = body.trim().split(/\s+(?=\w+\s+\w+)/g).map((a: string) => a.trim()).filter(Boolean);
      return `${name} {\n${attrs.map((a: string) => `    ${a}`).join("\n")}\n}`;
    });
    const c = {
      kw: "var(--pm-code-keyword)",
      entity: "var(--pm-code-function)",
      type: "var(--pm-code-number)",
      attr: "var(--pm-code-text)",
      rel: "var(--pm-code-string)",
      punct: "var(--pm-code-punct)",
      comment: "var(--pm-code-comment)",
    };

    return formatted.split("\n").map((line, i) => {
      const trimmed = line.trim();
      const indent = line.match(/^\s*/)?.[0] || "";
      let content: React.ReactNode;

      if (trimmed === "erDiagram" || trimmed.startsWith("direction")) {
        content = <span style={{ color: c.kw, fontWeight: 600 }}>{line}</span>;
      } else if (trimmed.match(/^\w+\s*\{$/)) {
        content = (
          <>
            {indent}
            <span style={{ color: c.entity, fontWeight: 600 }}>{trimmed.replace(/\s*\{$/, "")}</span>{" "}
            <span style={{ color: c.punct }}>{"{"}</span>
          </>
        );
      } else if (trimmed === "}") {
        content = (
          <>
            {indent}
            <span style={{ color: c.punct }}>{"}"}</span>
          </>
        );
      } else if (trimmed.match(/^\w+\s+\w+/) && !trimmed.includes("||") && !trimmed.includes("{")) {
        const parts = trimmed.split(/\s+/);
        content = (
          <>
            {indent}
            <span style={{ color: c.type }}>{parts[0]}</span> <span style={{ color: c.attr }}>{parts.slice(1).join(" ")}</span>
          </>
        );
      } else if (trimmed.match(/^\w+\s+[\|{}o\-\.]+\s+\w+\s*:/)) {
        const m = trimmed.match(/^(\w+)\s+([\|{}o\-\.]+)\s+(\w+)\s*:\s*(.+)$/);
        content = m ? (
          <>
            {indent}
            <span style={{ color: c.entity }}>{m[1]}</span> <span style={{ color: c.punct }}>{m[2]}</span>{" "}
            <span style={{ color: c.entity }}>{m[3]}</span> <span style={{ color: c.punct }}>:</span>{" "}
            <span style={{ color: c.rel }}>{m[4]}</span>
          </>
        ) : (
          <span style={{ color: c.attr }}>{line}</span>
        );
      } else if (trimmed.startsWith("%%") || trimmed.startsWith("#")) {
        content = <span style={{ color: c.comment, fontStyle: "italic" }}>{line}</span>;
      } else {
        content = trimmed ? <span style={{ color: c.attr }}>{line}</span> : "\u00A0";
      }

      return (
        <div key={i} className="flex min-h-[22px] leading-[22px]">
          <div className="w-10 shrink-0 pr-4 text-right text-xs text-[var(--pm-code-line)] select-none">{i + 1}</div>
          <div className="flex-1">{content}</div>
        </div>
      );
    });
  };

  const canvasHeight = isExpanded ? "75vh" : "460px";
  const showSource = mode === "source" || !!parseError;

  const tabBtn = (m: ViewMode, icon: React.ReactNode, label: string) => (
    <button
      type="button"
      onClick={() => setMode(m)}
      className={cn(
        "flex h-7 items-center gap-1.5 rounded-md px-2.5 text-xs font-medium transition-colors [&_svg]:size-3.5",
        mode === m ? "bg-pm-card text-pm-fg shadow-[0_1px_2px_rgba(0,0,0,0.06)]" : "text-pm-muted hover:text-pm-fg",
      )}
    >
      {icon}
      {label}
    </button>
  );

  const tool = "grid size-7 place-items-center rounded-md text-pm-muted transition-colors hover:bg-pm-card hover:text-pm-fg [&_svg]:size-3.5";

  return (
    <div className="flex w-full flex-col gap-3">
      {/* Summary + toolbar */}
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex rounded-lg border border-pm-line bg-pm-shell p-0.5">
          {tabBtn("diagram", <Network />, "Diagram")}
          {tabBtn("source", <Code2 />, "Source")}
        </div>

        <div className="flex items-center gap-2">
          {!showSource && (
            <div className="flex items-center rounded-lg border border-pm-line bg-pm-shell p-0.5">
              <button type="button" onClick={zoomOut} className={tool} title="Zoom out">
                <Minus />
              </button>
              <span className="w-11 text-center text-[11px] font-medium text-pm-fg/70 tabular-nums">{Math.round(scale * 100)}%</span>
              <button type="button" onClick={zoomIn} className={tool} title="Zoom in">
                <Plus />
              </button>
              <span className="mx-0.5 h-4 w-px bg-pm-line" />
              <button type="button" onClick={() => fitToScreen(svgDimensions.width, svgDimensions.height)} className={tool} title="Fit to view">
                <Scan />
              </button>
            </div>
          )}
          <div className="flex items-center rounded-lg border border-pm-line bg-pm-shell p-0.5">
            {mermaidSvg && (
              <button type="button" onClick={downloadSvg} className={tool} title="Download SVG">
                <Download />
              </button>
            )}
            <button type="button" onClick={() => setIsExpanded((x) => !x)} className={tool} title={isExpanded ? "Shrink" : "Make taller"}>
              {isExpanded ? <Minimize /> : <Expand />}
            </button>
          </div>
        </div>
      </div>

      {/* Canvas or source */}
      {showSource ? (
        <div className="overflow-auto rounded-xl border border-pm-line bg-pm-code py-3 font-mono text-[13px] whitespace-pre" style={{ height: canvasHeight }}>
          {parseError && mode === "diagram" && (
            <div className="mx-4 mb-3 rounded-lg border border-pm-danger/30 bg-pm-danger/5 px-3 py-2 font-sans text-xs whitespace-normal text-pm-danger">
              <strong>Couldn&apos;t draw the diagram.</strong> {parseError.split("\n")[0]} Showing the source instead.
            </div>
          )}
          {formatSource(processedMermaid)}
        </div>
      ) : (
        <div
          ref={containerRef}
          className={cn(
            "pm-er relative flex touch-none items-center justify-center overflow-hidden rounded-xl border border-pm-line bg-pm-code transition-[height] duration-300",
            isDragging ? "cursor-grabbing" : "cursor-grab",
          )}
          style={{
            height: canvasHeight,
            backgroundImage: "radial-gradient(circle, var(--pm-line) 1px, transparent 1px)",
            backgroundSize: "22px 22px",
          }}
          onPointerDown={onPointerDown}
          onPointerMove={onPointerMove}
          onPointerUp={stopDrag}
          onPointerCancel={stopDrag}
        >
          {!isLoaded && <div className="absolute inset-0 m-auto size-6 animate-spin rounded-full border-2 border-pm-line border-t-pm-primary" />}
          <div className={cn("size-full transition-opacity duration-500", isLoaded ? "opacity-100" : "opacity-0")}>
            <div
              className="pointer-events-none flex size-full items-center justify-center"
              style={{
                transform: `translate(${position.x}px, ${position.y}px) scale(${scale})`,
                transformOrigin: "center",
                transition: isDragging ? "none" : "transform 0.1s ease-out",
              }}
              dangerouslySetInnerHTML={{ __html: mermaidSvg }}
            />
          </div>
          <div className="pointer-events-none absolute bottom-2.5 left-2.5 flex items-center gap-1.5 rounded-md border border-pm-line bg-pm-card/90 px-2 py-1 text-[10.5px] font-medium text-pm-muted backdrop-blur-sm">
            <Hand className="size-3" />
            Drag to pan · Ctrl + scroll to zoom
          </div>
          <style>{`
            .pm-er svg { overflow: visible !important; }
            .pm-er text.er.entityName, .pm-er .entityLabel, .pm-er .er.entityLabel { font-weight: 700 !important; font-family: "Geist Mono", monospace !important; }
            .pm-er path.er.relationshipLine, .pm-er .relationshipLine { stroke: var(--pm-muted) !important; stroke-width: 1.4px !important; }
            .pm-er rect.er.entityBox { rx: 6px; ry: 6px; }
          `}</style>
        </div>
      )}

      {/* Tables */}
      {entities.length > 0 && (
        <div className="flex flex-wrap items-center gap-1.5">
          <span className="mr-1 flex items-center gap-1.5 text-xs text-pm-muted">
            <Table2 className="size-3.5" />
            <span className="font-semibold text-pm-fg tabular-nums">{entities.length}</span> tables ·{" "}
            <span className="font-semibold text-pm-fg tabular-nums">{relationshipCount}</span> relationships
          </span>
          {entities.map((e) => (
            <span
              key={e}
              onMouseEnter={() => setHighlight(e)}
              onMouseLeave={() => setHighlight(null)}
              className={cn(
                "rounded-md border px-2 py-0.5 font-mono text-[11px] transition-colors",
                highlight === e ? "border-pm-primary/40 bg-pm-primary/10 text-pm-accent" : "border-pm-line bg-pm-shell/60 text-pm-fg/75",
              )}
            >
              {e}
            </span>
          ))}
        </div>
      )}
    </div>
  );
}
